#!/usr/bin/env python3
"""S.A.M party members: extract each vanilla class's starting kit from Barony's initClass()
into the table framework/sam_party.cpp includes.

Usage: python tools/gen_party_loadouts.py ../Barony/src/charclass.cpp > framework/sam_party_loadouts.inc

initClass() hands a PLAYER their kit with itemPickup/useItem on a live player, which a monster
cannot go through, so sam_party.cpp gives a party member the same items from this table instead.
Re-run it after a Barony update so a party member's kit keeps matching a player's. A custom
class needs none of this: its starting_items are read from its JSON."""
import re, sys
text = open(sys.argv[1], encoding='utf-8', errors='replace').read()
text = re.sub(r'/\*.*?\*/', lambda m: '\n' * m.group(0).count('\n'), text, flags=re.S)
lines = [re.sub(r'//.*', '', l) for l in text.split('\n')]
start = next(i for i, l in enumerate(lines) if l.startswith('void initClass(const int player)'))
pat = re.compile(r'newItem\(\s*([A-Z_0-9]+)\s*,\s*([A-Z_]+)\s*,\s*(-?\d+)\s*,\s*(\d+)\s*,\s*([^,]+?)\s*,\s*(true|false)')
branch = re.compile(r'^\s*(?:else\s+)?if\s*\(\s*client_classes\[player\]\s*==\s*(CLASS_[A-Z]+)\s*\)\s*$')
depth = 0; cls = None; out = {}; pending = None; cond_depth = None; chain_done = False
def flush():
    global pending
    if pending: out[cls].append(pending); pending = None
for i in range(start, len(lines)):
    l = lines[i]
    m = branch.match(l)
    if m and depth == 1 and not chain_done:
        flush(); cls = m.group(1); out[cls] = []; cls_depth = depth
    elif depth == 1 and cls and l.strip() and not l.strip().startswith(('{', '}', 'else')) and not chain_done:
        flush(); chain_done = True; cls = None
    if cls and not chain_done:
        mm = pat.search(l)
        if mm:
            flush()
            # an item nested in an extra 'if' inside the class block is conditional (race/appearance/local)
            ctx = ''.join(lines[max(start, i - 8):i])
            conditional = bool(re.search(r'playerRace|stat_appearance|RACE_', ctx)) and depth > 3
            pending = dict(type=mm.group(1), status=mm.group(2), bless=int(mm.group(3)), count=int(mm.group(4)),
                           ident=mm.group(6), equip=False, conditional=conditional)
        elif pending and 'useItem(' in l:
            pending['equip'] = True
    depth += l.count('{') - l.count('}')
    if depth == 0 and i > start + 2:
        break
flush()
print('// Generated by tools/gen_party_loadouts.py from Barony\'s charclass.cpp initClass(). Do not edit by hand.')
print('// { class, item, status, beatitude, count, identified, equip }')
for c, items in out.items():
    for it in items:
        if it['conditional']:
            print(f'// skipped race-conditional: {c} {it["type"]}')
            continue
        print(f'{{ {c}, {it["type"]}, {it["status"]}, {it["bless"]}, {it["count"]}, {it["ident"]}, {"true" if it["equip"] else "false"} }},')
sys.stderr.write(' '.join(f'{c[6:]}={len(v)}' for c, v in out.items()) + '\n')
