// Writes src/data/itemLooks.js: how many looks (appearances) each vanilla item type has.
//
//   node scripts/gen-item-looks.mjs "<Barony folder>/items/items.json"
//
// An item's `appearance` number picks one of its pictures: the game shows image
// (appearance % number of images), and a cloak has 4, so appearance 0 to 3. The count is the length of
// each item's `item_images` list in the game's items.json. Only items with more than one look are
// written. Left out are the types whose appearance is NOT a look but game data (the same list as
// samItemAppearanceIsGameplay in framework/sam_js_runtime.cpp): a book's contents, a letter, a feather's
// or a scepter's charges, a loot bag's contents, a robot's health, a spell item's spell, and a spell tome's
// spell (TOME_*, 9 pictures, the spell it teaches is the number). Spellbooks are left out too: their cover
// is chosen by the spell's school and difficulty (getItemVariationFromSpellbookOrTome in items.cpp),
// whatever the number says. The rubber duck is left out because its model follows appearance divided by
// the player count. The Class Editor has its own picker for readable books.
// Run it again if the game adds items, and commit the result with it.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.resolve(here, '../src/data/itemLooks.js');
const NOT_LOOKS = new Set([
  'READABLE_BOOK', 'SPELL_ITEM', 'SCROLL_MAIL', 'ENCHANTED_FEATHER', 'MAGICSTAFF_SCEPTER',
  'TOOL_PLAYER_LOOT_BAG', 'TOOL_SENTRYBOT', 'TOOL_SPELLBOT', 'TOOL_GYROBOT', 'TOOL_DUMMYBOT',
  'TOOL_DUCK',   // 16 pictures, but its model follows appearance / MAXPLAYERS, so it is not a plain look
]);

const src = process.argv[2];
if (!src) { console.error('usage: node scripts/gen-item-looks.mjs <path to Barony items/items.json>'); process.exit(2); }

const items = JSON.parse(readFileSync(src, 'utf8')).items;
const schema = JSON.parse(readFileSync(path.resolve(here, '../../schemas/class.schema.json'), 'utf8'));
const known = new Set(schema.definitions.itemType.enum);

const byCount = new Map();
let skippedUnknown = 0;
for (const [name, def] of Object.entries(items)) {
  const n = (def.item_images || []).length;
  const type = name.toUpperCase();
  if (n < 2 || NOT_LOOKS.has(type) || type.startsWith('SPELLBOOK_') || type.startsWith('TOME_')) continue;
  if (!known.has(type)) { skippedUnknown += 1; console.warn(`skipped ${type}: not an item type in class.schema.json`); continue; }
  if (!byCount.has(n)) byCount.set(n, []);
  byCount.get(n).push(type);
}

const groups = [...byCount.entries()].sort((a, b) => a[0] - b[0]).map(([n, types]) => {
  const lines = [];
  let line = '   ';
  for (const t of types.sort()) {
    const piece = ` '${t}',`;
    if ((line + piece).length > 110) { lines.push(line); line = '   '; }
    line += piece;
  }
  lines.push(line);
  return `  ${n}: [\n${lines.join('\n')}\n  ],`;
});

writeFileSync(OUT, `/*
 * GENERATED by scripts/gen-item-looks.mjs from the game's items/items.json: edit that, not this file.
 *
 * How many looks a vanilla item has. An item's \`appearance\` number picks one of its pictures (the game
 * shows image \`appearance % looks\`): a cloak has 4, so 0 to 3. Items with one look are not listed.
 */
const GROUPS = {
${groups.join('\n')}
};

/** type name -> number of looks, for the items that have more than one. */
export const ITEM_LOOKS = Object.fromEntries(
  Object.entries(GROUPS).flatMap(([n, types]) => types.map((t) => [t, Number(n)])),
);

/** How many looks an item type has (1 when it has no choice). */
export const looksOf = (type) => ITEM_LOOKS[type] || 1;
`);
const total = [...byCount.values()].reduce((s, a) => s + a.length, 0);
console.log(`wrote ${path.relative(process.cwd(), OUT)}: ${total} item types with more than one look${skippedUnknown ? `, ${skippedUnknown} skipped` : ''}`);
